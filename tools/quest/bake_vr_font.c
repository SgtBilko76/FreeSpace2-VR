/* Bakes the VR keyboard glyphs (printable ASCII) from a TrueType font into a
 * C header of 8-bit coverage bitmaps, so the Quest build needs no font file
 * at runtime.
 *
 *   cc -O2 -I code/graphics/paths/nanovg tools/quest/bake_vr_font.c -lm -o /tmp/bake_vr_font
 *   /tmp/bake_vr_font /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf 40 \
 *       > code/graphics/openxr_quest_keyboard_font.h
 *
 * The default font is DejaVu Sans Bold (Bitstream Vera / DejaVu license,
 * free to embed and redistribute). */
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

#include <stdio.h>
#include <stdlib.h>

int main(int argc, char** argv) {
	FILE*          file;
	long           size;
	unsigned char* ttf;
	stbtt_fontinfo font;
	float          scale;
	int            pixel_height;
	int            ascent, descent, gap;
	int            offset = 0;
	int            column = 0;

	if (argc < 3) {
		fprintf(stderr, "usage: %s font.ttf pixel_height\n", argv[0]);
		return 1;
	}
	pixel_height = atoi(argv[2]);
	file         = fopen(argv[1], "rb");
	if (!file) {
		perror(argv[1]);
		return 1;
	}
	fseek(file, 0, SEEK_END);
	size = ftell(file);
	fseek(file, 0, SEEK_SET);
	ttf = malloc((size_t)size);
	if (fread(ttf, 1, (size_t)size, file) != (size_t)size) {
		return 1;
	}
	fclose(file);
	if (!stbtt_InitFont(&font, ttf, stbtt_GetFontOffsetForIndex(ttf, 0))) {
		return 1;
	}
	scale = stbtt_ScaleForPixelHeight(&font, (float)pixel_height);
	stbtt_GetFontVMetrics(&font, &ascent, &descent, &gap);

	printf("/* Generated by tools/quest/bake_vr_font.c from DejaVu Sans Bold, %d px.\n", pixel_height);
	printf(" * DejaVu fonts: Bitstream Vera license (free to embed). Do not edit. */\n");
	printf("#ifndef VR_KEYBOARD_FONT_H\n#define VR_KEYBOARD_FONT_H\n\n");
	printf("#include <stdint.h>\n\n");
	printf("typedef struct VrGlyph {\n\tint16_t w, h, xoff, yoff, advance;\n\tint32_t offset;\n} VrGlyph;\n\n");
	printf("enum { VR_FONT_FIRST = 32, VR_FONT_LAST = 126, VR_FONT_ASCENT = %d, VR_FONT_HEIGHT = %d };\n\n",
		   (int)(ascent * scale + 0.5f), pixel_height);

	printf("static const uint8_t vr_font_bits[] = {\n");
	int offsets[128], ws[128], hs[128], xo[128], yo[128], adv[128];
	for (int ch = 32; ch <= 126; ++ch) {
		int            w = 0, h = 0, xoff = 0, yoff = 0, advance, lsb;
		unsigned char* bits = stbtt_GetCodepointBitmap(&font, scale, scale, ch, &w, &h, &xoff, &yoff);
		stbtt_GetCodepointHMetrics(&font, ch, &advance, &lsb);
		offsets[ch] = offset;
		ws[ch]      = w;
		hs[ch]      = h;
		xo[ch]      = xoff;
		yo[ch]      = yoff;
		adv[ch]     = (int)(advance * scale + 0.5f);
		for (int i = 0; i < w * h; ++i) {
			printf("%d,", bits[i]);
			if (++column == 40) {
				printf("\n");
				column = 0;
			}
		}
		offset += w * h;
		stbtt_FreeBitmap(bits, NULL);
	}
	printf("0};\n\n");
	printf("static const VrGlyph vr_font_glyphs[VR_FONT_LAST - VR_FONT_FIRST + 1] = {\n");
	for (int ch = 32; ch <= 126; ++ch) {
		printf("\t{%d, %d, %d, %d, %d, %d},\n", ws[ch], hs[ch], xo[ch], yo[ch], adv[ch], offsets[ch]);
	}
	printf("};\n\n#endif\n");
	free(ttf);
	return 0;
}
